import {test,before,after,beforeEach} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import {createSession,leaderboard,adminOverview,ensurePlayer,playerCode} from '../src/lib/store';
import {saveRule,updateRule,deleteRule,listRules} from '../src/lib/exclusions';
import {normalizeIP,hashIP} from '../src/lib/security';
const pg=new PGlite();
const db={query:async(sql:string,p:unknown[]=[]) => (await pg.query(sql,p)).rows as Record<string,any>[]};
process.env.IP_HMAC_SECRET='test-only-exclusion-secret-'.repeat(3);
before(async()=>{for(const file of ['001_init.sql','002_anonymous_exclusions.sql'])await pg.exec(await readFile(new URL('../db/'+file,import.meta.url),'utf8'));});
beforeEach(async()=>{await pg.exec('TRUNCATE sessions,players,exclusion_rules,rate_limits RESTART IDENTITY CASCADE');});
after(async()=>pg.close());
const start=(p:string,hash='a'.repeat(64))=>({id:randomUUID(),playerId:p,startKey:randomUUID(),nickname:'legacy-private-name',country:null,region:null,ipHash:hash,isTest:false});
test('anonymous numbers persist by browser, increase by first player, and do not truncate above 999',async()=>{
 const p=randomUUID(),q=randomUUID();
 assert.equal(playerCode((await ensurePlayer(db,p)).number),'IP-001');
 await ensurePlayer(db,p);await createSession(db,start(p));
 assert.equal(playerCode((await ensurePlayer(db,q)).number),'IP-002');
 assert.equal(playerCode(1001),'IP-1001');
 const board=await leaderboard(db,'all',p);
 assert.equal(board.entries[0].playerCode,'IP-001');
 assert.equal('nickname' in board.entries[0],false);
 assert.equal('player_id' in board.entries[0],false);
});
test('same IP does not merge browsers; retroactive network exclusion and disabling are reversible',async()=>{
 const p=randomUUID(),q=randomUUID(),hash=hashIP('192.0.2.9');
 await createSession(db,start(p,hash));await createSession(db,start(q,hash));
 assert.equal((await leaderboard(db,'all',p)).total,2);
 const r=await saveRule(db,{kind:'ip',value:hash,label:'家中网络',retroactive:true});
 assert.equal((await leaderboard(db,'all',p)).total,0);
 assert.equal((await adminOverview(db,{})).stats.games,0);
 await updateRule(db,r.id,{enabled:false});
 assert.equal((await leaderboard(db,'all',p)).total,2);
 await updateRule(db,r.id,{enabled:true});await deleteRule(db,r.id);
 assert.equal((await leaderboard(db,'all',p)).total,2);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM sessions'))[0].n,2);
});
test('overlapping player/network exclusions must both be removed before restoring records',async()=>{
 const p=randomUUID(),s=start(p);await createSession(db,s);
 const a=await saveRule(db,{kind:'player',value:p,label:'当前设备',retroactive:true});
 const b=await saveRule(db,{kind:'ip',value:s.ipHash,label:'共享网络',retroactive:true});
 await updateRule(db,a.id,{enabled:false});
 assert.equal((await leaderboard(db,'all',p)).total,0);
 await deleteRule(db,b.id);
 assert.equal((await leaderboard(db,'all',p)).total,1);
});
test('future-only rules preserve older official records and formal/test filters are separate',async()=>{
 const p=randomUUID();const old=await createSession(db,start(p));
 await db.query("UPDATE sessions SET started_at=now()-interval '1 day' WHERE id=$1",[old.id]);
 await saveRule(db,{kind:'player',value:p,label:'测试设备',retroactive:false});
 await createSession(db,start(p));
 assert.equal((await adminOverview(db,{type:'official'})).records.length,1);
 assert.equal((await adminOverview(db,{type:'test'})).records.length,1);
 assert.equal((await adminOverview(db,{type:'all'})).records.length,2);
 const list=await listRules(db);assert.equal('value' in list[0],false);
});
test('canonical IP handles IPv6 and mapped addresses and rejects malformed input',()=>{
 assert.equal(normalizeIP('2001:0db8:0000:0000:0000:0000:0000:0001'),'2001:db8::1');
 assert.equal(normalizeIP('::ffff:192.0.2.9'),'192.0.2.9');
 assert.equal(hashIP('2001:db8::1'),hashIP('2001:0db8::1'));
 assert.throws(()=>normalizeIP('192.168.1.999'));
});
